# ============================ 行情工具 ============================
def _bars(rows: list[dict]) -> dict:
    return {
        "date": [r["date"] for r in rows],
        "high": [float(r["high"]) for r in rows],
        "low": [float(r["low"]) for r in rows],
        "close": [float(r["close"]) for r in rows],
        "volume": [float(r.get("volume") or 0) for r in rows],
    }


def regime(rows: list[dict]) -> dict:
    """区间形态：单边上涨 / 震荡 / 急跌 / 其他。规则写死。"""
    b = _bars(rows)
    cl, hi, lo = b["close"], b["high"], b["low"]
    ret = (cl[-1] / cl[0] - 1) * 100
    peak, mdd = cl[0], 0.0
    for c in cl:
        peak = max(peak, c)
        mdd = max(mdd, (peak - c) / peak * 100)
    amp = (max(hi) - min(lo)) / min(lo) * 100
    if ret > 15 and mdd < 10:
        reg = "单边上涨"
    elif ret < -15 and mdd > 20:
        reg = "急跌"
    elif abs(ret) <= 10 and amp > 15:
        reg = "震荡"
    else:
        reg = "其他"
    return {"ret": ret, "mdd": mdd, "amp": amp, "reg": reg,
            "start": b["date"][0], "end": b["date"][-1], "n": len(cl),
            "bh": (cl[-1] / cl[0] - 1) * 100}


def rsi(closes: list[float], n: int = 14) -> float:
    if len(closes) <= n:
        return 50.0
    gains = [max(closes[i] - closes[i - 1], 0) for i in range(1, len(closes))]
    losses = [max(closes[i - 1] - closes[i], 0) for i in range(1, len(closes))]
    ag, al = sum(gains[:n]) / n, sum(losses[:n]) / n
    for i in range(n, len(gains)):
        ag = (ag * (n - 1) + gains[i]) / n
        al = (al * (n - 1) + losses[i]) / n
    return 100.0 if al == 0 else 100 - 100 / (1 + ag / al)


def window_metrics(rows: list[dict]) -> dict:
    b = _bars(rows)
    cl, hi, lo, vol = b["close"], b["high"], b["low"], b["volume"]
    rets = [cl[i] / cl[i - 1] - 1 for i in range(1, len(cl))]
    mean = sum(rets) / len(rets)
    std = math.sqrt(sum((x - mean) ** 2 for x in rets) / max(len(rets) - 1, 1))
    neg = [x for x in rets if x < 0]
    nmean = sum(neg) / len(neg) if neg else 0.0
    nstd = math.sqrt(sum((x - nmean) ** 2 for x in neg) / max(len(neg) - 1, 1)) if neg else 0.0
    var95 = sorted(rets)[max(0, int(len(rets) * 0.05) - 1)] if rets else 0.0
    rg = regime(rows)
    return {
        "n": len(cl), "start": b["date"][0], "end": b["date"][-1],
        "price": cl[-1], "prev": cl[-2], "chg": (cl[-1] / cl[-2] - 1) * 100,
        "ret": rg["ret"], "mdd": rg["mdd"], "amp": rg["amp"],
        "vol": std * math.sqrt(252) * 100,
        "dvol": nstd * math.sqrt(252) * 100,
        "var95": var95 * 100,
        "maxdrop": min(rets) * 100,
        "down_days": sum(1 for x in rets if x < 0),
        "up_days": sum(1 for x in rets if x >= 0),
        "ma5": sum(cl[-5:]) / 5, "ma10": sum(cl[-10:]) / 10,
        "ma20": sum(cl[-20:]) / 20, "ma60": sum(cl[-60:]) / 60,
        "rsi": rsi(cl),
        "ret20": (cl[-1] / cl[-21] - 1) * 100 if len(cl) > 21 else 0.0,
        "high": max(hi), "low": min(lo),
        "pos": (cl[-1] - min(lo)) / (max(hi) - min(lo)) * 100 if max(hi) > min(lo) else 50.0,
        "amt20": sum(c * v for c, v in zip(cl[-20:], vol[-20:])) / 20 / 1e8,
        "vr": vol[-1] / (sum(vol[-20:]) / 20) if sum(vol[-20:]) else 0.0,
    }


def beta_vs_index(stock: list[dict], index: list[dict], n: int = 120) -> float:
    s = _bars(stock)["close"][-(n + 1):]
    i = _bars(index)["close"][-(n + 1):]
    sr = [s[k] / s[k - 1] - 1 for k in range(1, len(s))]
    ir = [i[k] / i[k - 1] - 1 for k in range(1, len(i))]
    m = min(len(sr), len(ir))
    sr, ir = sr[-m:], ir[-m:]
    mi = sum(ir) / m
    var = sum((x - mi) ** 2 for x in ir) / m
    return (sum((sr[k] - sum(sr) / m) * (ir[k] - mi) for k in range(m)) / m) / var if var else 1.0


