async def _run_bt(code: str, strategy: str, days: int, params: dict) -> dict:
    res = await run_strategy_backtest(code, strategy, params=params or {},
                                      initial_capital=INITIAL_CAPITAL, days=days)
    if res.get("warning"):
        raise RuntimeError(f"{code} {strategy} {days}d: {res['warning']}")
    trades = res["trades"]
    sells = [t for t in trades if t["action"] == "SELL"]
    buys = [t for t in trades if t["action"] == "BUY"]
    return {
        "metrics": res["metrics"], "trades": trades,
        "bars": res["bars_count"], "sells": len(sells), "wins": sum(
            1 for t in sells if float(t.get("pnl") or 0) > 0),
        "buys": len(buys), "last_action": trades[-1]["action"] if trades else "",
        "params": res.get("params") or {}, "warning": res.get("warning"),
    }


