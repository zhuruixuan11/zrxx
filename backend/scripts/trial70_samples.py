def _hold_numbers(fb: FactBook, rows: list[dict], invest: float, hold_n: int) -> dict:
    buy = float(rows[0]["close"])
    last = float(rows[-1]["close"])
    shares = int(invest / buy / LOT) * LOT
    cost = shares * buy
    value = shares * last
    pnl = value - cost
    breakeven = buy * (1 + COMMISSION / 100) / (1 - (COMMISSION + STAMP) / 100)
    peak, mdd = buy, 0.0
    for r in rows:
        peak = max(peak, float(r["close"]))
        mdd = max(mdd, (peak - float(r["close"])) / peak * 100)
    vals = {
        "buy": fb.n("hold_buy_price", buy, 2),
        "last": fb.n("hold_last_price", last, 2),
        "shares": fb.n("hold_shares", shares, 0),
        "cost": fb.n("hold_cost", cost, 2),
        "value": fb.n("hold_value", value, 2),
        "pnl": fb.n("hold_pnl", pnl, 2, signed=True),
        "pct": fb.n("hold_pnl_pct", (last / buy - 1) * 100, 2, signed=True),
        "breakeven": fb.n("hold_breakeven", breakeven, 2),
        "mdd": fb.n("hold_mdd", mdd, 2),
        "days": fb.n("hold_days", hold_n, 0),
    }
    return vals


